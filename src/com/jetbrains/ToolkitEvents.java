package com.jetbrains;

import java.awt.EventQueue;

/**
 * Allows an application that has pushed its own {@link java.awt.EventQueue} implementation to receive
 * events generated by AWT via that queue's {@link java.awt.EventQueue#postEvent(java.awt.AWTEvent)} method.
 * <p>
 * By default, events generated by AWT itself enter the bottom-most (root) {@link java.awt.EventQueue} of the system
 * event queue stack via its {@link java.awt.EventQueue#postEvent(java.awt.AWTEvent)} method, which are then forwarded
 * to the queues up the stack without calling that method again.
 * <p>
 * Events posted by user applications via methods like {@link java.awt.EventQueue#invokeLater(java.lang.Runnable)}
 * are not affected by this API.
 */
@Service
@Provided
public interface ToolkitEvents {
    /**
     * Sets the {@link java.awt.EventQueue}, which {@link java.awt.EventQueue#postEvent(java.awt.AWTEvent)} method
     * is called for events generated by AWT itself.
     * <p>
     * Upon the return of this method, it is guaranteed that every new AWT event will be posted to the passed event queue
     * via the {@link java.awt.EventQueue#postEvent(java.awt.AWTEvent)} method.
     * This method may block until the posting of previously generated events completes.
     * <p>
     * {@code queue} must remain on the stack for the duration of it being used as the AWT's target event queue.
     *
     * @param queue new target queue, or {@code null} to restore the default (root) queue
     * @return the previous target queue, never {@code null}
     * @throws java.lang.IllegalArgumentException if passed queue is not on the system event queue stack
     * @throws java.lang.IllegalStateException if the system event queue is not initialized for the calling thread
     */
    EventQueue setTargetEventQueue(EventQueue queue);
}
